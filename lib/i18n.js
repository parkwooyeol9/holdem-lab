function lookup(lang, key) {
  const parts = key.split(".");
  let cur = STRINGS[lang] || STRINGS.ko;
  for (const part of parts) {
    cur = cur?.[part];
    if (cur == null) break;
  }
  if (typeof cur === "string") return cur;
  cur = STRINGS.en;
  for (const part of parts) {
    cur = cur?.[part];
    if (cur == null) return key;
  }
  return typeof cur === "string" ? cur : key;
}

function format(template, vars) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? "" : String(vars[name])));
}

const LangContext = createContext({ lang: "ko", t: (key, vars) => format(lookup("ko", key), vars), setLang: () => {} });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState("ko");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("hl-lang");
      if (saved === "en" || saved === "ko") setLangState(saved);
    } catch {}
  }, []);

  useEffect(() => {
    try {
      localStorage.setItem("hl-lang", lang);
    } catch {}
    if (typeof document !== "undefined") document.documentElement.lang = lang === "en" ? "en" : "ko";
  }, [lang]);

  const value = useMemo(
    () => ({
      lang,
      setLang: setLangState,
      t: (key, vars) => format(lookup(lang, key), vars)
    }),
    [lang]
  );

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useT() {
  return useContext(LangContext);
}
